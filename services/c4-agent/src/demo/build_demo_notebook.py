"""Generate notebooks/03_demo.ipynb (agent chat + decoding modes side by side).

    python -m src.demo.build_demo_notebook

The notebook carries a compressed copy of the C4 code and of Component 1's
published data files (read-only copy, for the mocks), so Colab needs no access
to the private repo. The mock services run in-process; no servers are started.
"""

from __future__ import annotations

import base64
import gzip
import json
from pathlib import Path

from training.build_notebook import code, md

ROOT = Path(__file__).resolve().parents[2]  # services/c4-agent
C1_DATA = ROOT.parent / "c1-review-engine" / "data"
OUT = ROOT / "notebooks" / "03_demo.ipynb"

CODE_FILES = [
    "src/config.py", "src/data_access.py", "src/geo.py", "src/hotel_directory.py", "src/synthesizer.py",
    "src/agent.py", "src/tools/clients.py", "src/tools/definitions.py", "src/tools/executor.py",
    "src/mocks/c1_mock.py", "src/mocks/c2_mock.py", "src/mocks/c3_mock.py", "src/demo/app.py",
    "training/fc_format.py", "evaluation/decoding.py", "evaluation/scoring.py",
    "evaluation/data/tourism_testset_v1.jsonl",
]
EMPTY_INITS = ["src/__init__.py", "src/tools/__init__.py", "src/mocks/__init__.py", "src/demo/__init__.py",
               "training/__init__.py", "evaluation/__init__.py"]
C1_FILES = ["hotels_seed.csv", "hotel_aspect_profiles.json", "destinations_seed.csv"]


def _pack(data: bytes) -> str:
    return base64.b64encode(gzip.compress(data, mtime=0)).decode()


def bundle() -> dict[str, str]:
    files = {p: _pack((ROOT / p).read_bytes()) for p in CODE_FILES}
    files.update({p: _pack(b"") for p in EMPTY_INITS})
    files.update({f"c1data/{n}": _pack((C1_DATA / n).read_bytes()) for n in C1_FILES})
    return files


def build() -> dict:
    files = bundle()
    cells = [
        md("""
# C4 - demo: tourism agent + decoding modes side by side

1. **Agent chat** - the fine-tuned model decides which component to call (C1 reviews, C2 hotels,
   C3 itinerary, web search); the answer is written only from the tool results.
2. **Decoding modes side by side** - the same question under the four decoding modes, with
   validity, correctness against the gold answer and latency.

C1 uses Component 1's real published scores; C2 prices and C3 routes/restaurants are mock data
(labelled as such). Run on a **T4 GPU**: `Runtime -> Run all`, then open the **public link**
printed at the bottom (valid for 72 hours). Generated by `python -m src.demo.build_demo_notebook`.
"""),
        code("""
# ==== Settings ====
BASE_MODEL = "Qwen/Qwen2.5-0.5B-Instruct"
ADAPTER = "Kavindu03dev/c4-qwen2.5-0.5b-fc-lora"
"""),
        code("""
!nvidia-smi --query-gpu=name,memory.total --format=csv
!pip -q install -U "transformers>=4.46" "peft>=0.13" "accelerate>=1.0" xgrammar jsonschema gradio fastapi httpx
"""),
        code("""
from google.colab import userdata
from huggingface_hub import login
login(token=userdata.get("HF_TOKEN").strip())
"""),
        md("### Unpack the C4 code and C1's data (compressed copy from the repo)"),
        code("FILES = " + json.dumps(files) + """

import base64, gzip, os, sys
from pathlib import Path
ROOT = Path("/content/c4")
for rel, blob in FILES.items():
    p = ROOT / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_bytes(gzip.decompress(base64.b64decode(blob)))
os.environ["C1_DATA_DIR"] = str(ROOT / "c1data")
sys.path.insert(0, str(ROOT))
print("unpacked", len(FILES), "files")
"""),
        md("### Load the model and start the demo"),
        code("""
from fastapi.testclient import TestClient
from evaluation.decoding import Generator
from src.demo.app import build_ui
from src.mocks.c1_mock import app as c1
from src.mocks.c2_mock import app as c2
from src.mocks.c3_mock import app as c3
from src.tools.clients import ToolClients
from src.tools.executor import ToolExecutor
import json

llm = Generator(BASE_MODEL, ADAPTER)
executor = ToolExecutor(ToolClients(c1=TestClient(c1), c2=TestClient(c2), c3=TestClient(c3)))
testset = [json.loads(l) for l in open(ROOT / "evaluation/data/tourism_testset_v1.jsonl", encoding="utf-8")]
demo = build_ui(llm, executor, testset)
demo.launch(share=True, debug=True)
"""),
    ]
    return {
        "cells": cells,
        "metadata": {"accelerator": "GPU", "colab": {"provenance": [], "gpuType": "T4"},
                     "kernelspec": {"display_name": "Python 3", "name": "python3"}, "language_info": {"name": "python"}},
        "nbformat": 4,
        "nbformat_minor": 0,
    }


def main() -> None:
    OUT.write_text(json.dumps(build(), indent=1) + "\n", encoding="utf-8")
    print(f"Wrote {OUT} ({OUT.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
