def route_file_version(path: Path):
    """Ignore access time: merely reading an old route must not make it fresh."""
    stat = path.stat()
    return stat.st_mtime_ns, stat.st_ctime_ns, stat.st_size, stat.st_ino


def load_day_route(day: int, previous_versions: dict):
    """Read a newly written day route after the route stage, under PIPELINE_LOCK."""
    path = ROUTE_FOLDER / f"day_{day}_route.geojson"
    try:
        if route_file_version(path) == previous_versions.get(path):
            raise ValueError("file was not regenerated by the current route stage")
        with path.open(encoding="utf-8") as file:
            collection = json.load(file)
        if collection["type"] != "FeatureCollection" or len(collection["features"]) != 1:
            raise ValueError("expected a single route feature")
        feature = collection["features"][0]
        properties = feature["properties"]
        geometry = feature["geometry"]
        if feature["type"] != "Feature" or properties["day"] != day:
            raise ValueError("route feature day does not match the itinerary day")
        coordinates = geometry["coordinates"]
        if (
            geometry["type"] != "LineString"
            or not isinstance(coordinates, list)
            or len(coordinates) < 2
        ):
            raise ValueError("expected LineString coordinates")
        for pair in coordinates:
            if not isinstance(pair, list) or len(pair) != 2 or not all(
                type(value) in (int, float) and math.isfinite(value) for value in pair
            ):
                raise ValueError("invalid route coordinate pair")
        metrics = [properties["distance_km"], properties["duration_min"]]
        if not all(
            type(value) in (int, float) and math.isfinite(value) and value >= 0
            for value in metrics
        ):
            raise ValueError("invalid route distance or duration")
        return {
            "geometry": coordinates,
            "distance_km": float(metrics[0]),
            "duration_min": float(metrics[1]),
        }
    except (OSError, ValueError, KeyError, TypeError, IndexError) as error:
        LOGGER.warning("Route unavailable for day %s (%s): %s", day, path.name, error)
        return None


