@app.post("/plan-itinerary")
def plan_itinerary(
    request: PlanRequest,
):

    with PIPELINE_LOCK:

        try:

            # --------------------------------------------
            # SAVE COMPONENT 2 INPUT
            # --------------------------------------------

            INPUT_FILE.parent.mkdir(
                parents=True,
                exist_ok=True,
            )

            request_data = (
                request.model_dump(exclude_none=True)
            )

            with open(
                INPUT_FILE,
                "w",
                encoding="utf-8",
            ) as file:

                json.dump(
                    request_data,
                    file,
                    indent=2,
                    ensure_ascii=False,
                )


            # --------------------------------------------
            # RUN COMPONENT 3 PIPELINE
            # --------------------------------------------

            pipeline_logs = []
            route_stage_succeeded = False
            previous_route_versions = {}

            for script in PIPELINE_SCRIPTS:

                # ----------------------------------------
                # OPTIONAL MEDICAL ACCESS STAGE
                # ----------------------------------------
                #
                # Run medical-access computation after
                # POI scoring and immediately before
                # itinerary optimization.
                #
                # Normal tourists skip this stage.

                if (
                    script.name
                    == "04_optimize_multi_day.py"
                    and request.medical_support.required
                ):

                    run_script(
                        MEDICAL_ACCESS_SCRIPT
                    )

                    pipeline_logs.append(
                        {
                            "stage":
                                MEDICAL_ACCESS_SCRIPT.name,

                            "status":
                                "success",

                            "reason":
                                "medical_support_required",
                        }
                    )


                # ----------------------------------------
                # NORMAL COMPONENT 3 PIPELINE STAGE
                # ----------------------------------------

                if script.name == "03_build_route_geometry.py":
                    # Snapshot before generation; untouched files from older
                    # requests must never be attached to this response.
                    previous_route_versions = {
                        path: route_file_version(path)
                        for path in ROUTE_FOLDER.glob("day_*_route.geojson")
                    }

                run_script(
                    script
                )

                if script.name == "03_build_route_geometry.py":
                    route_stage_succeeded = True

                pipeline_logs.append(
                    {
                        "stage":
                            script.name,

                        "status":
                            "success",
                    }
                )


            # --------------------------------------------
            # CHECK OUTPUT FILES
            # --------------------------------------------

            if not ITINERARY_FILE.exists():

                raise RuntimeError(
                    "optimized_itinerary.csv "
                    "was not generated."
                )


            if not RESTAURANT_FILE.exists():

                raise RuntimeError(
                    "final_ranked_restaurants.csv "
                    "was not generated."
                )


            # --------------------------------------------
            # LOAD ITINERARY
            # --------------------------------------------

            itinerary_df = pd.read_csv(
                ITINERARY_FILE
            )


            # --------------------------------------------
            # LOAD RESTAURANT RANKING
            # --------------------------------------------

            restaurants_df = pd.read_csv(
                RESTAURANT_FILE
            )


            # Top 5 restaurants for each day.

            top_restaurants_df = (
                restaurants_df[
                    restaurants_df[
                        "final_day_rank"
                    ]
                    <= 5
                ]
                .copy()
            )


            # --------------------------------------------
            # GROUP RESULTS BY DAY
            # --------------------------------------------

            days = []

            day_numbers = sorted(
                itinerary_df[
                    "day"
                ]
                .dropna()
                .unique()
            )


            for day_number in day_numbers:

                day_itinerary = (
                    itinerary_df[
                        itinerary_df[
                            "day"
                        ]
                        == day_number
                    ]
                    .sort_values(
                        "stop_order"
                    )
                )


                day_restaurants = (
                    top_restaurants_df[
                        top_restaurants_df[
                            "day"
                        ]
                        == day_number
                    ]
                    .sort_values(
                        "final_day_rank"
                    )
                )


                days.append(
                    {
                        "day":
                            int(
                                day_number
                            ),

                        "stops":
                            dataframe_to_records(
                                day_itinerary
                            ),

                        "recommended_restaurants":
                            dataframe_to_records(
                                day_restaurants
                            ),

                        "route": (
                            load_day_route(int(day_number), previous_route_versions)
                            if route_stage_succeeded else None
                        ),
                    }
                )


            # --------------------------------------------
            # MEDICAL SUMMARY FOR API RESPONSE
            # --------------------------------------------

            medical_summary = {
                "required":
                    request.medical_support.required,

                "priority":
                    request.medical_support.priority,

                "average_hospital_access_min":
                    None,

                "best_hospital_access_min":
                    None,

                "worst_hospital_access_min":
                    None,
            }


            if (
                request.medical_support.required
                and
                "emergency_hospital_travel_time_min"
                in itinerary_df.columns
            ):

                medical_times = pd.to_numeric(
                    itinerary_df[
                        "emergency_hospital_travel_time_min"
                    ],
                    errors="coerce",
                ).dropna()


                if not medical_times.empty:

                    medical_summary[
                        "average_hospital_access_min"
                    ] = round(
                        float(
                            medical_times.mean()
                        ),
                        2,
                    )

                    medical_summary[
                        "best_hospital_access_min"
                    ] = round(
                        float(
                            medical_times.min()
                        ),
                        2,
                    )

                    medical_summary[
                        "worst_hospital_access_min"
                    ] = round(
                        float(
                            medical_times.max()
                        ),
                        2,
                    )


            # --------------------------------------------
            # RESPONSE
            # --------------------------------------------

            return {
                "status":
                    "success",

                "trip_id":
                    request.trip_id,

                "hotel":
                    request.hotel.model_dump(),

                "trip":
                    request.trip.model_dump(exclude_none=True),

                "medical_support":
                    medical_summary,

                "days":
                    days,

                "pipeline":
                    pipeline_logs,
            }


        except Exception as error:

            raise HTTPException(
                status_code=500,
                detail=str(
                    error
                ),
            )
