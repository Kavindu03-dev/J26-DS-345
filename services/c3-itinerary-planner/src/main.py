class MedicalSupportInput(BaseModel):

    # False means normal itinerary planning.
    required: bool = False

    # Supported priorities:
    # normal
    # high
    priority: str = "normal"

    @field_validator(
        "priority"
    )
    @classmethod
    def validate_priority(
        cls,
        value,
    ):

        value = value.lower().strip()

        allowed = {
            "normal",
            "high",
        }

        if value not in allowed:
            raise ValueError(
                "medical_support priority "
                "must be 'normal' or 'high'."
            )

        return value


class PlanRequest(BaseModel):

    context: dict | None = None

    accessibility: dict[str, bool] | None = None

    @model_validator(mode="before")
    @classmethod
    def adapt_external_c2(cls, value):
        if isinstance(value, dict) and "for_c3" in value:
            return adapt_c2_handoff(value)
        if isinstance(value, dict) and "selected_hotel" in value:
            return adapt_c2_to_c3(value)
        return value

    trip_id: str

    hotel: HotelInput

    trip: TripInput

    attraction_preferences: (
        AttractionPreferences
    )

    restaurant_preferences: (
        RestaurantPreferences
    )

    # Optional medical-support-aware routing.
    #
    # If the field is omitted completely,
    # the system behaves as:
    #
    # required = False
    # priority = normal

    medical_support: MedicalSupportInput = Field(
        default_factory=MedicalSupportInput
    )

    @field_validator(
        "trip"
    )
    @classmethod
    def validate_trip_time(
        cls,
        value,
    ):

        if (
            value.day_end_hour
            <= value.day_start_hour
        ):
            raise ValueError(
                "day_end_hour must be later "
                "than day_start_hour."
            )

        return value


